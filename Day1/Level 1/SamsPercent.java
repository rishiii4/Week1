import java.util.*;
public class SamsPercent{
	public static void main(String args[]){
		
		//Marks in PCM
		int math = 94;
		int physics = 95;
		int chemistry = 96;
		
		//Calculating Average Percent
		int averagePercent = (math + physics + chemistry) / 3;
		
		System.out.print("Sam’s average mark in PCM is " + averagePercent);
	}	
}