import java.util.*;
public class KiloToMile{
	public static void main(String args[]){
		
		//Distance in Kilometer
		float kilometer = 10.8f;
		
		float miles = 1.6f;
		
		//Converting Kilometer to miles
		float inMiles = kilometer * miles ;
		
		System.out.print("The distance "+ kilometer + "km in miles is " + inMiles);
	}	
}